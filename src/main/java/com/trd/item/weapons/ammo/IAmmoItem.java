package com.trd.item.weapons.ammo;

public interface IAmmoItem {
    String getCaliber();
    float getDamage();
    float getSpeed();
    boolean isPiercing();

    /**
     * Трассерный ли патрон.
     * <p>
     * Разница чисто внешняя: трассер тянет за собой светящийся след, поэтому он
     * рисуется всегда максимальной яркости и своей моделью, а обычный боезаряд —
     * обычной моделью и при обычном освещении. На урон, скорость и пробитие флаг
     * не влияет: у трассера ровно те же характеристики, что у его обычного
     * варианта.
     */
    boolean isTracer();
}